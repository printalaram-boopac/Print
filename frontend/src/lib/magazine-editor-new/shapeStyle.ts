function toClipPath(points: [number, number][]): string {
  return `polygon(${points.map(([x, y]) => `${x}% ${y}%`).join(', ')})`;
}

/** Real clip-path/border-radius masking for a shape — not a decorative border on top of a rect. */
export function getShapeMaskStyle(shapeType: ShapeType | undefined, borderRadius: number | undefined): CSSProperties {
  switch (shapeType) {
    case 'circle':
    case 'ellipse':
      return { borderRadius: '50%' };
    case 'pill':
      return { borderRadius: 9999 };
    case 'arch':
      return { borderRadius: '50% 50% 0 0' };
    case 'blob':
      return { borderRadius: '62% 38% 55% 45% / 55% 45% 62% 38%' };
    case 'rounded-rectangle':
      return { borderRadius: `${borderRadius ?? 12}%` };
    case 'rectangle':
    case 'square':
      return {};
    default:
      return shapeType && SHAPE_POLYGONS[shapeType] ? { clipPath: toClipPath(SHAPE_POLYGONS[shapeType]!) } : {};
  }
}

/** Same idea, for image frames (Frames section) — masks the photo itself. */
export function getFrameMaskStyle(frameShape: FrameShape | undefined, borderRadius: number | undefined): CSSProperties {
  switch (frameShape) {
    case 'circle':
    case 'oval':
      return { borderRadius: '50%' };
    case 'arch':
      return { borderRadius: '50% 50% 0 0' };
    case 'rounded':
      return { borderRadius: `${borderRadius ?? 8}%` };
    case 'polaroid':
      return { borderRadius: 2 };
    case 'heart':
      return { clipPath: toClipPath(SHAPE_POLYGONS.heart!) };
    case 'star':
      return { clipPath: toClipPath(SHAPE_POLYGONS.star!) };
    case 'diamond':
      return { clipPath: toClipPath(SHAPE_POLYGONS.diamond!) };
    case 'badge':
      return { clipPath: toClipPath(SHAPE_POLYGONS.badge!) };
    default:
      return { borderRadius: `${borderRadius ?? 0}%` };
  }
}
